  // 中心の線を細かい点に（なめらかなら Catmull-Rom）
  function sample(pts, smooth) {
    const out = [];
    const n = pts.length;
    if (smooth && n > 2) {
      for (let i = 0; i < n - 1; i++) {
        const p0 = pts[Math.max(0, i - 1)], p1 = pts[i], p2 = pts[i + 1], p3 = pts[Math.min(n - 1, i + 2)];
        const steps = 12;
        for (let s = 0; s < steps; s++) {
          const u = s / steps, u2 = u * u, u3 = u2 * u;
          out.push([0, 1].map(k => 0.5 * (2 * p1[k] + (-p0[k] + p2[k]) * u + (2 * p0[k] - 5 * p1[k] + 4 * p2[k] - p3[k]) * u2 + (-p0[k] + 3 * p1[k] - 3 * p2[k] + p3[k]) * u3)));
        }
      }
      out.push(pts[n - 1].slice());
    } else {
      for (let i = 0; i < n - 1; i++) {
        const a = pts[i], b = pts[i + 1], steps = Math.max(2, Math.round(Math.hypot(b[0] - a[0], b[1] - a[1]) / 6));
        for (let s = 0; s < steps; s++) out.push([a[0] + (b[0] - a[0]) * s / steps, a[1] + (b[1] - a[1]) * s / steps, s === 0 && i > 0]);
      }
      out.push(pts[n - 1].slice());
    }
    return out;
  }
