  function strokePath(type, pts, smooth, W) {
    const P = sample(pts, smooth), n = P.length;
    const len = [0];
    for (let i = 1; i < n; i++) len.push(len[i - 1] + Math.hypot(P[i][0] - P[i - 1][0], P[i][1] - P[i - 1][1]));
    const total = len[n - 1] || 1, L = [], R = [], Wd = [];
    for (let i = 0; i < n; i++) {
      const a = P[Math.max(0, i - 1)], b = P[Math.min(n - 1, i + 1)];
      let tx = b[0] - a[0], ty = b[1] - a[1];
      const tl = Math.hypot(tx, ty) || 1; tx /= tl; ty /= tl;
      let w = W * prof(type, len[i] / total) / 2;
      // 折れ目は角が細らないように広げる
      if (P[i][2] && i > 0 && i < n - 1) {
        const ax = P[i][0] - P[i - 1][0], ay = P[i][1] - P[i - 1][1], bx = P[i + 1][0] - P[i][0], by = P[i + 1][1] - P[i][1];
        const c = (ax * bx + ay * by) / ((Math.hypot(ax, ay) * Math.hypot(bx, by)) || 1);
        w /= Math.max(0.62, Math.sqrt((1 + c) / 2));
      }
      Wd.push(w);
      L.push([P[i][0] - ty * w, P[i][1] + tx * w]);
      R.push([P[i][0] + ty * w, P[i][1] - tx * w]);
    }
    let d = `M${f1(L[0][0])} ${f1(L[0][1])}`;
    for (let i = 1; i < n; i++) d += `L${f1(L[i][0])} ${f1(L[i][1])}`;
    const we = Wd[n - 1], ws = Wd[0];
    d += we > 0.6 ? `A${f1(we)} ${f1(we)} 0 0 0 ${f1(R[n - 1][0])} ${f1(R[n - 1][1])}` : `L${f1(R[n - 1][0])} ${f1(R[n - 1][1])}`;
    for (let i = n - 2; i >= 0; i--) d += `L${f1(R[i][0])} ${f1(R[i][1])}`;
    d += ws > 0.6 ? `A${f1(ws)} ${f1(ws)} 0 0 0 ${f1(L[0][0])} ${f1(L[0][1])}` : '';
    return d + 'Z';
  }
